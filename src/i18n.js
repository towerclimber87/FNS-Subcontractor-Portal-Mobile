function normalizeLanguageCode(value) {
  return String(value || '')
    .replace('_', '-')
    .split('-')[0]
    .trim()
    .toLowerCase();
}

export function getDeviceLanguageCode() {
  try {
    const settings = NativeModules?.SettingsManager?.settings || {};
    const appleLanguage = Array.isArray(settings.AppleLanguages) ? settings.AppleLanguages[0] : null;
    const iosLocale = settings.AppleLocale || appleLanguage;
    const androidLocale = NativeModules?.I18nManager?.localeIdentifier;
    const locale = Platform.OS === 'ios' ? iosLocale : androidLocale || iosLocale;
    return normalizeLanguageCode(locale || 'en') || 'en';
  } catch (_error) {
    return 'en';
  }
}

export function isSpanishDevice() {
  return getDeviceLanguageCode() === 'es';
}

export function t(text, values = {}) {
  const source = String(text ?? '');
  const translated = isSpanishDevice() ? (ES[source] || source) : source;
  return translated.replace(/\{(\w+)\}/g, (_match, key) => {
    const value = values?.[key];
    return value === undefined || value === null ? '' : String(value);
  });
}

export function translateOptions(options = []) {
  return options.map((option) => {
    if (typeof option === 'string') return t(option);
    if (!option || typeof option !== 'object') return option;
    return {
      ...option,
      label: option.label ? t(option.label) : option.label,
      title: option.title ? t(option.title) : option.title,
      text: option.text ? t(option.text) : option.text,
    };
  });
}
